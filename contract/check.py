def schema_refs(node, path=()):
    """Yield (path, property name, property schema) for every object property."""
    if isinstance(node, dict):
        for name, sub in node.get("properties", {}).items():
            yield path, name, sub
        for k, v in node.items():
            yield from schema_refs(v, path + (k,))
    elif isinstance(node, list):
        for i, v in enumerate(node):
            yield from schema_refs(v, path + (i,))


def check_schema(schema: dict, contract: dict) -> None:
    jsonschema.Draft202012Validator.check_schema(schema)
    defs = schema["$defs"]
    verbs = [v for v, s in contract["verbs"].items() if s["kind"] == "act"]
    act_names = verbs + list(contract["structural_acts"])
    if defs["verb"]["enum"] != act_names:
        fail(f"schema verb enum {defs['verb']['enum']} != contract acts {act_names}")
    for name, states in state_sets(contract).items():
        enum = defs["state"]["properties"].get(name, {}).get("enum")
        if enum != states:
            fail(f"schema states for {name} {enum} != {states}")
    for field, limit in contract["limits"].items():
        got = defs.get(field, {}).get("maxLength")
        if got != limit:
            fail(f"schema limit {field} {got} != contract {limit}")
    # Every field the review names is held to its limit.
    for kind, names in contract["limit_fields"].items():
        for path, name, sub in schema_refs(defs):
            if name in names and path[:1] != ("verb",):
                if kind == "result" and path[:1] != ("witness",):
                    continue
                if sub.get("$ref") != f"#/$defs/{kind}":
                    fail(f"schema: field {name} at {'/'.join(map(str, path))} is not limited as {kind}")
    if defs["level"]["examples"] != contract["levels"]["initial"]:
        fail("schema level examples != contract initial levels")
    if defs["reference"]["properties"]["kind"]["enum"] != list(contract["references"]["kinds"]):
        fail("schema reference kinds != contract reference kinds")
    if schema["properties"]["protocol"]["const"] != contract["bedrock"]:
        fail("schema protocol const != contract version")
    for verb in act_names:
        if f"payload_{verb}" not in defs:
            fail(f"schema has no payload definition for {verb}")
    for noun, spec in contract["nouns"].items():
        if spec["prefix"] and not re.match(defs[f"id_{noun}"]["pattern"], f"{spec['prefix']}-1"):
            fail(f"schema id pattern for {noun} does not admit {spec['prefix']}-1")
    # A Plan holds only its member nouns: every field naming a Plan member
    # admits exactly those ids.
    member = {"anyOf": [{"$ref": f"#/$defs/id_{n}"} for n in contract["group"]["Plan"]["members"]]}
    if defs.get("id_plan_member", {}).get("anyOf") != member["anyOf"]:
        fail(f"schema id_plan_member {defs.get('id_plan_member')} != {member}")
    regroup = defs["payload_regroup"]["properties"]
    waits = defs["waits"]["items"]["properties"]
    for where, sub in (
        ("plan.members", defs["plan"]["properties"]["members"]["items"]),
        ("payload_regroup.add_members", regroup["add_members"]["items"]),
        ("payload_regroup.remove_members", regroup["remove_members"]["items"]),
        ("waits.member", waits["member"]),
        ("waits.upon", waits["upon"]),
    ):
        if sub != {"$ref": "#/$defs/id_plan_member"}:
            fail(f"schema {where} admits {sub}, not only Plan members")
    out = contract["outcomes"]
    if defs["payload_judge"]["properties"]["verdict"]["enum"] != out["judge"]:
        fail("schema judge verdicts != contract judge outcomes")
    if defs["payload_evaluate"]["properties"]["outcome"]["enum"] != out["evaluate"]:
        fail("schema evaluate outcomes != contract evaluate outcomes")
    decide = defs["payload_decide"]["properties"]["outcomes"]["items"]["properties"]["outcome"]["enum"]
    if decide != sum(out["decide"].values(), []):
        fail("schema decide outcomes != contract decide outcomes")
    raw = SCHEMA.read_text()
    for w in REMOVED_PHASE_WORDS:
        if re.search(rf"\b{w}\b", raw):
            fail(f"schema: removed two-phase word {w!r} appears")
    for w in REMOVED_STATE_WORDS:
        if f'"{w}"' in raw:
            fail(f"schema: removed state word {w!r} appears")


