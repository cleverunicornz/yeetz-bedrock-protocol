"""Check that the Bedrock v2 prose, machine-readable contract, JSON Schema and
worked examples agree.

Run from the repository root:

    uv run --no-project --with pyyaml --with jsonschema python contract/check.py

Exit 0 when everything agrees; otherwise every disagreement is printed and the
exit code is 1. The reference projector below replays each example's acts and,
after every act, rebuilds every record's state from the acts that still stand
(the latest standing act wins). It records every transition it observes, so the
check also proves that the transition table is consistent with the act rules,
that every listed transition is exercised by at least one example, that no act
changes a record outside its one-step reach (no cascading), and that no act is
ever generated by a state change.
"""

