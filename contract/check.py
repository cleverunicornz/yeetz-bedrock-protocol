ROOT = Path(__file__).resolve().parent
PROSE = ROOT / "bedrock-v2.md"
CONTRACT = ROOT / "bedrock-v2.yaml"
SCHEMA = ROOT / "bedrock-v2.schema.json"
EXAMPLES = ROOT / "examples"
NO_LOOP_EXAMPLE = "contract/examples/10-no-recursive-invalidation.yaml"

# Review 1 removed these state words; none may come back as a state, an
# outcome, or a backticked word in the prose.
REMOVED_STATE_WORDS = [
    "in_force", "open", "addressing", "closed", "tolerated", "evaluating",
    "assuring", "current", "accepted", "declined", "retired",
]
# Review 1 removed two-phase acts.
REMOVED_PHASE_WORDS = ["begun", "completed"]
WITHDRAWN = ("superseded", "revoked")

errors: list[str] = []


def fail(msg: str) -> None:
    errors.append(msg)


