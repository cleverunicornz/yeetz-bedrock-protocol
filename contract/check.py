def state_sets(contract: dict) -> dict[str, list[str]]:
    out = {n: s["states"] for n, s in contract["nouns"].items()}
    out["Plan"] = contract["group"]["Plan"]["states"]
    return out


def made_by(contract: dict, noun: str) -> str:
    if noun == "Plan":
        return contract["group"]["Plan"]["made_by"]
    return contract["nouns"][noun]["made_by"]


def first_state(contract: dict, noun: str) -> str:
    """The past tense of the verb that makes the noun, or the exception's first word."""
    rule = contract["state_rule"]
    if noun in rule["exception"]:
        return rule["exception"][noun][0]
    return rule["past_tense"][made_by(contract, noun)]


def check_contract(contract: dict) -> None:
    """Review 1, rule 2: a state is the past tense of the last verb applied;
    the one exception is the Promise; every noun may also be superseded or
    revoked (a Witness only revoked). No removed word returns."""
    rule = contract["state_rule"]
    past = rule["past_tense"]
    exception = rule["exception"]
    sets = state_sets(contract)
    acts = [v for v, s in contract["verbs"].items() if s["kind"] in ("act", "transition")]
    acts += list(contract["structural_acts"])
    if sorted(past) != sorted(set(acts) - set(rule["no_state"])):
        fail(f"state rule: past_tense covers {sorted(past)}, not every state-giving act")

    for noun, states in sets.items():
        first = first_state(contract, noun)
        if noun in exception:
            allowed = set(exception[noun]) | set(WITHDRAWN)
        else:
            allowed = set(past.values())
        if states[0] != first:
            fail(f"state rule: {noun}'s first state {states[0]} != {first}")
        for s in states:
            if s not in allowed:
                fail(f"state rule: {noun} state {s} is not the past tense of a verb")
            if s in REMOVED_STATE_WORDS:
                fail(f"state rule: {noun} uses removed state word {s}")
        withdrawn = [s for s in states if s in WITHDRAWN]
        want = ["revoked"] if noun in rule["never_superseded"] + ["Plan"] else list(WITHDRAWN)
        if withdrawn != want:
            fail(f"state rule: {noun} withdrawn states {withdrawn} != {want}")
        from_tr = []
        for t in contract["transitions"]:
            if t["noun"] == noun and t["to"] not in from_tr:
                from_tr.append(t["to"])
        if from_tr != states:
            fail(f"state rule: {noun} states {states} != states reached by transitions {from_tr}")

    for t in contract["transitions"]:
        noun, to = t["noun"], t["to"]
        if t.get("recompute"):
            if not set(t["by"]) <= set(WITHDRAWN_BY) or to in WITHDRAWN:
                fail(f"transition {t}: a recomputation follows only revoke or supersede")
            continue
        if noun in exception and to in exception[noun]:
            continue
        for v in t["by"]:
            want = first_state(contract, noun) if not t["from"] else past.get(v)
            if to != want:
                fail(f"state rule: {noun} {t['from']} -> {to} by {v}; the state must be {want}")

    for act, spec in contract["outcomes"].items():
        values = sum(spec.values(), []) if isinstance(spec, dict) else spec
        for v in values:
            if v in REMOVED_STATE_WORDS or v in set(past.values()):
                fail(f"outcomes: {act} outcome {v} is a state word")

    raw = CONTRACT.read_text()
    for w in REMOVED_PHASE_WORDS:
        if re.search(rf"\b{w}\b", raw):
            fail(f"contract: removed two-phase word {w!r} appears")

    reach = contract["one_step"]
    all_acts = [v for v, s in contract["verbs"].items() if s["kind"] == "act"]
    all_acts += list(contract["structural_acts"])
    if sorted(reach) != sorted(all_acts):
        fail(f"one_step: covers {sorted(reach)}, not every act {sorted(all_acts)}")
    for v, tokens in reach.items():
        for tok in tokens:
            if tok not in REACH_TOKENS:
                fail(f"one_step: {v} names unknown reach {tok}")
    if contract["recomputation"]["generates_acts"] is not False:
        fail("recomputation: must never generate acts")


WITHDRAWN_BY = ("revoke", "supersede")


