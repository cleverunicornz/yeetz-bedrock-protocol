class Refused(Exception):
    def __init__(self, code: str, msg: str):
        super().__init__(msg)
        self.code = code


def noun_of(record_id: str, contract: dict) -> str:
    for name, spec in contract["nouns"].items():
        if record_id.startswith(spec["prefix"] + "-"):
            return name
    if record_id.startswith(contract["group"]["Plan"]["prefix"] + "-"):
        return "Plan"
    raise Refused("unknown_id", f"unknown record id {record_id}")


MADE_KEYS = ("invariant", "gap", "candidate", "decision", "promise", "oracle", "witness", "reference", "plan")


class Projector:
    """Replays acts. After every act it rebuilds every record's state from the
    acts that still stand, so it never moves a state by hand."""

    def __init__(self, contract: dict):
        self.c = contract
        self.past = contract["state_rule"]["past_tense"]
        self.state: dict[str, str] = {}
        self.record: dict[str, dict] = {}
        self.hist: dict[str, list[dict]] = {}  # record -> state-giving acts, in order
        self.author: dict[str, tuple[str, datetime]] = {}  # record -> (agent, created)
        self.subjects: dict[str, list[str]] = {}  # Decision -> its outcome subjects
        self.judged: set[tuple[str, str]] = set()  # (Witness, Oracle)
        self.log: list[dict] = []
        self.applied: set[tuple] = set()
        self.allowed = {
            (t["noun"], f, t["to"], v)
            for t in contract["transitions"]
            for v in t["by"]
            for f in (t["from"] or [None])
        }

    # -- the state rule ----------------------------------------------------

    def withdrawn(self, rid: str) -> bool:
        return any(e["verb"] in WITHDRAWN_BY for e in self.hist.get(rid, []))

    def stands(self, e: dict) -> bool:
        return e.get("rests_on") is None or not self.withdrawn(e["rests_on"])

    def derive(self, rid: str) -> str:
        h = self.hist[rid]
        for e in h:
            if e["verb"] in WITHDRAWN_BY:
                return e["state"]  # revoke and supersede always stand
        if noun_of(rid, self.c) == "Promise":
            verdicts = [
                e for e in h
                if e["verb"] == "judge" and self.stands(e) and e["verdict"] != "inconclusive"
            ]
            return "assured" if verdicts and verdicts[-1]["verdict"] == "holds" else "asserted"
        return [e for e in h if self.stands(e)][-1]["state"]

    def give(self, rid: str, act: dict, state: str, **extra) -> None:
        if self.withdrawn(rid) and act["verb"] not in WITHDRAWN_BY:
            raise Refused("transition_not_allowed", f"{rid} is withdrawn; {act['verb']} does not apply")
        self.hist.setdefault(rid, []).append({"act": act["id"], "verb": act["verb"], "state": state, **extra})

    def rebuild(self, verb: str) -> None:
        for rid in self.hist:
            new, old = self.derive(rid), self.state.get(rid)
            if new == old:
                continue
            noun = noun_of(rid, self.c)
            by = "assure" if noun == "Promise" and new == "assured" and verb == "judge" else verb
            key = (noun, old, new, by)
            if key not in self.allowed:
                raise Refused("transition_not_allowed", f"{noun} {rid}: {old} -> {new} by {by}")
            self.applied.add(key)
            self.state[rid] = new

    # -- acts ----------------------------------------------------------------

    def create(self, rec: dict, noun: str, act: dict) -> None:
        rid = rec["id"]
        if noun_of(rid, self.c) != noun:
            raise Refused("wrong_noun", f"{rid} is not a {noun}")
        if rid in self.hist:
            raise Refused("duplicate_id", f"{rid} exists")
        self.record[rid] = copy.deepcopy(rec)
        self.author[rid] = (act["actor"]["agent"], when(act))
        self.give(rid, act, first_state(self.c, noun))

    def need(self, rid: str, noun: str) -> dict:
        if rid not in self.record or noun_of(rid, self.c) != noun:
            raise Refused("missing_input", f"{rid} is not a recorded {noun}")
        return self.record[rid]

    def latest_outcome(self, rid: str) -> str | None:
        decided = [e for e in self.hist[rid] if e["verb"] == "decide" and self.stands(e)]
        return decided[-1]["outcome"] if decided else None

    def add_member(self, members: list[str], m: str) -> None:
        noun = noun_of(m, self.c)
        if noun not in self.c["group"]["Plan"]["members"]:
            raise Refused("bad_member", f"{m} cannot be a Plan member")
        self.need(m, noun)
        if m in members:
            raise Refused("bad_member", f"{m} is already a member")
        members.append(m)

    def check_wait(self, members: list[str], w: dict) -> None:
        if w["member"] not in members or w["upon"] not in members:
            raise Refused("bad_member", f"waits_on {w} names a non-member")

    def making_act(self, act: dict) -> dict:
        """The act that made the record an act's edit window belongs to: the
        act itself when it made a record, the end of its amend chain when it
        is an amendment. Refused when that act made no record."""
        target = act
        while target["verb"] == "amend":
            tid = target["payload"]["target_act"]
            found = next((a for a in self.log if a["id"] == tid), None)
            if found is None:
                raise Refused("missing_input", f"{tid} is not a recorded act")
            target = found
        if not any(isinstance(target["payload"].get(k), dict) for k in MADE_KEYS):
            raise Refused("not_amendable", f"{target['id']} ({target['verb']}) made no record to amend")
        return target

    def apply(self, act: dict) -> None:
        saved = copy.deepcopy(
            (self.state, self.record, self.hist, self.author, self.subjects, self.judged, self.applied)
        )
        try:
            self.log.append(act)
            self._apply(act)
            self.rebuild(act["verb"])
        except Refused:
            self.log.pop()
            (self.state, self.record, self.hist, self.author, self.subjects, self.judged, self.applied) = saved
            raise

    def _apply(self, act: dict) -> None:
        v, p = act["verb"], act["payload"]
        if v == "stipulate":
            for b in p.get("basis", []):
                self.need(b, noun_of(b, self.c))
            self.create(p["invariant"], "Invariant", act)
        elif v == "declare":
            if "arose_in" in p and not any(a["id"] == p["arose_in"] for a in self.log):
                raise Refused("missing_input", f"arose_in {p['arose_in']} is not a recorded act")
            self.create(p["gap"], "Gap", act)
        elif v == "formulate":
            for r in p["responds_to"]:
                self.need(r, noun_of(r, self.c))
            self.create(p["candidate"], "Candidate", act)
        elif v == "evaluate":
            cid = p["candidate"]
            self.need(cid, "Candidate")
            for r in p.get("findings", []):
                self.need(r, "Reference")
            self.give(cid, act, self.past[v], outcome=p["outcome"])
        elif v == "decide":
            for r in p.get("considered", []):
                self.need(r, noun_of(r, self.c))
            did = p["decision"]["id"]
            self.create(p["decision"], "Decision", act)
            self.subjects[did] = []
            for o in p.get("outcomes", []):
                subj, out = o["subject"], o["outcome"]
                noun = noun_of(subj, self.c)
                self.need(subj, noun)
                if out not in self.c["outcomes"]["decide"].get(noun, []):
                    raise Refused("bad_outcome", f"{out} is not an outcome for a {noun}")
                self.give(subj, act, self.past[v], outcome=out, rests_on=did)
                self.subjects[did].append(subj)
        elif v == "mint":
            basis = p["basis"]
            if "decision" in basis:
                self.need(basis["decision"], "Decision")
            else:
                self.need(basis["instruction"], "Reference")
            if "from_candidate" in p:
                if "decision" not in basis:
                    raise Refused("missing_input", "a Promise minted from a Candidate cites the Decision")
                self.need(p["from_candidate"], "Candidate")
                if self.latest_outcome(p["from_candidate"]) != "accept":
                    raise Refused("missing_input", "the Candidate was not accepted")
                accepted_by = [
                    e["rests_on"] for e in self.hist[p["from_candidate"]]
                    if e["verb"] == "decide" and e["outcome"] == "accept" and self.stands(e)
                ]
                if basis["decision"] not in accepted_by:
                    raise Refused("wrong_basis", f"{basis['decision']} did not accept {p['from_candidate']}")
            for g in p.get("addresses", []):
                self.need(g, "Gap")
            self.create(p["promise"], "Promise", act)
        elif v == "define":
            o = p["oracle"]
            self.need(o["judges"], "Promise")
            self.create(o, "Oracle", act)
        elif v == "produce":
            w = p["witness"]
            self.need(w["observes"], "Promise")
            for e in w["evidence"]:
                self.need(e, "Reference")
            self.create(w, "Witness", act)
        elif v == "refine":
            t = p["target"]
            noun = noun_of(t, self.c)
            self.need(t, noun)
            if noun == "Witness":
                w = p.get("witness")
                if not w or w["observes"] != self.record[t]["observes"]:
                    raise Refused("missing_input", "refining a Witness produces a new Witness of the same Promise")
                if self.withdrawn(t):
                    raise Refused("witness_revoked", f"{t} is revoked; produce a new Witness instead")
                for e in w["evidence"]:
                    self.need(e, "Reference")
                self.create(w, "Witness", act)
            elif noun in ("Gap", "Candidate"):
                if "sighting" not in p:
                    raise Refused("missing_input", "refining a Gap or Candidate adds a sighting")
                for e in p["sighting"].get("evidence", []):
                    self.need(e, "Reference")
            else:
                raise Refused("not_refinable", f"a {noun} is not refined")
        elif v == "judge":
            pid, oid, wid = p["promise"], p["oracle"], p["witness"]
            self.need(pid, "Promise")
            o = self.need(oid, "Oracle")
            w = self.need(wid, "Witness")
            if o["judges"] != pid or w["observes"] != pid:
                raise Refused("mismatched_inputs", "the Oracle and Witness must concern the judged Promise")
            if self.withdrawn(oid):
                raise Refused("oracle_not_in_force", f"{oid} is {self.state[oid]}")
            if self.withdrawn(wid):
                raise Refused("witness_revoked", f"{wid} is revoked")
            if (wid, oid) in self.judged:
                raise Refused("already_judged", f"{wid} is already judged against {oid}; a rejudge needs a new Witness or a new Oracle")
            if p["verdict"] == "does_not_hold" and not p.get("failure_evidence"):
                raise Refused("missing_input", "does_not_hold cites the demonstrated in-scope failure")
            self.judged.add((wid, oid))
            self.give(wid, act, self.past[v])
            self.give(pid, act, self.past[v], verdict=p["verdict"], rests_on=wid)
        elif v in WITHDRAWN_BY:
            t = p["target"]
            noun = noun_of(t, self.c)
            self.need(t, noun)
            if self.withdrawn(t):
                raise Refused("transition_not_allowed", f"{t} is already {self.state[t]}")
            if v == "supersede":
                s = p["successor"]
                if noun_of(s, self.c) != noun:
                    raise Refused("wrong_noun", "a successor is the same noun")
                self.need(s, noun)
                if self.withdrawn(s):
                    raise Refused("successor_not_current", f"{s} is {self.state[s]}")
            self.give(t, act, self.past[v])
        elif v == "store":
            self.create(p["reference"], "Reference", act)
        elif v == "group":
            plan = p["plan"]
            members: list[str] = []
            for m in plan["members"]:
                self.add_member(members, m)
            for w in plan.get("waits_on", []):
                self.check_wait(members, w)
            self.create(plan, "Plan", act)
        elif v == "regroup":
            plan = self.need(p["plan"], "Plan")
            members = plan["members"]
            waits = plan.setdefault("waits_on", [])
            # Removals first, then additions, so a member leaves with its
            # links and arrives with them in one act.
            for w in p.get("remove_waits", []):
                if w not in waits:
                    raise Refused("bad_member", f"{p['plan']} has no waits_on link {w}")
                waits.remove(w)
            for m in p.get("remove_members", []):
                if m not in members:
                    raise Refused("bad_member", f"{m} is not a member of {p['plan']}")
                if any(m in (w["member"], w["upon"]) for w in waits):
                    raise Refused("bad_member", f"{m} is still named by a waits_on link of {p['plan']}")
                members.remove(m)
            for m in p.get("add_members", []):
                self.add_member(members, m)
            for w in p.get("add_waits", []):
                self.check_wait(members, w)
                if w in waits:
                    raise Refused("bad_member", f"{p['plan']} already has waits_on link {w}")
                waits.append(w)
            self.give(p["plan"], act, self.past[v])
        elif v == "relate":
            for r in (p["from"], p["to"]):
                if not r.startswith("scope:"):
                    self.need(r, noun_of(r, self.c))
        elif v == "amend":
            # The window runs from the act that made the record; an amendment
            # of an amendment corrects the same record and never extends it.
            target = self.making_act(act)
            if target["actor"]["agent"] != act["actor"]["agent"]:
                raise Refused("not_author", "only the author amends within the edit window")
            window = self.c["parameters"]["edit_window_seconds"]
            if (when(act) - when(target)).total_seconds() > window:
                raise Refused("edit_window_closed", "the edit window has closed; supersede or revoke")
        else:
            raise Refused("unknown_verb", v)


# The records an act may change, by the tokens of the contract's one_step map.
REACH_TOKENS = {
    "made": lambda proj, p: {p[k]["id"] for k in MADE_KEYS if isinstance(p.get(k), dict)},
    "candidate": lambda proj, p: {p["candidate"]} if isinstance(p.get("candidate"), str) else set(),
    "subjects": lambda proj, p: {o["subject"] for o in p.get("outcomes", [])},
    "witness": lambda proj, p: {p["witness"]} if isinstance(p.get("witness"), str) else set(),
    "promise": lambda proj, p: {p["promise"]} if isinstance(p.get("promise"), str) else set(),
    "plan": lambda proj, p: {p["plan"]} if isinstance(p.get("plan"), str) else set(),
    "target": lambda proj, p: {p["target"]} if "target" in p else set(),
    "promise_of_witness": lambda proj, p: (
        {proj.record[p["target"]]["observes"]} if p.get("target", "").startswith("W-") else set()
    ),
    "subjects_of_decision": lambda proj, p: set(proj.subjects.get(p.get("target", ""), [])),
}


def reach(contract: dict, proj: Projector, act: dict) -> set[str]:
    out: set[str] = set()
    for tok in contract["one_step"][act["verb"]]:
        out |= REACH_TOKENS[tok](proj, act["payload"])
    return out


def when(act: dict) -> datetime:
    return datetime.fromisoformat(act["recorded_at"].replace("Z", "+00:00"))


def merge(base: dict, over: dict) -> dict:
    out = copy.deepcopy(base)
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def check_examples(schema: dict, contract: dict) -> tuple[set[tuple], set[str]]:
    validator = jsonschema.Draft202012Validator(
        schema, format_checker=jsonschema.Draft202012Validator.FORMAT_CHECKER
    )
    exercised: set[tuple] = set()
    refusals: set[str] = set()
    files = sorted(EXAMPLES.glob("*.yaml"))
    if not files:
        fail("examples: none found")
    for path in files:
        raw = path.read_text()
        for w in REMOVED_PHASE_WORDS:
            if re.search(rf"\b{w}\b", raw):
                fail(f"{path.name}: removed two-phase word {w!r} appears")
        ex = yaml.safe_load(raw)
        name = path.name
        proj = Projector(contract)
        refused = None
        crashed = False
        trace: dict[str, list[str]] = {}
        for i, raw_act in enumerate(ex["acts"]):
            act = merge(ex.get("defaults", {}), raw_act)
            invalid = list(validator.iter_errors(act))
            for err in invalid:
                fail(f"{name} act {i} ({act.get('id')}): schema: {err.message} at {list(err.absolute_path)}")
            if invalid:
                break
            before = dict(proj.state)
            try:
                proj.apply(act)
            except Refused as r:
                refused = (i, r)
                break
            except Exception as e:  # a defect in the example or the projector
                fail(f"{name} act {i} ({act.get('id')}): projector raised {type(e).__name__}: {e}")
                crashed = True
                break
            if "edit_window_closes_at" in act:
                try:
                    made = proj.making_act(act)
                except Refused as r:
                    fail(f"{name} act {i} ({act['id']}): carries edit_window_closes_at but {r}")
                    continue
                closes = when(made) + timedelta(seconds=contract["parameters"]["edit_window_seconds"])
                if when({"recorded_at": act["edit_window_closes_at"]}) != closes:
                    fail(f"{name} act {i} ({act['id']}): edit_window_closes_at {act['edit_window_closes_at']}"
                         f" != {made['id']} recorded_at + window ({closes.isoformat()})")
            # Rule 5a: recomputation never creates work.
            if len(proj.log) != i + 1:
                fail(f"{name} act {i}: the log holds {len(proj.log)} acts after {i + 1} were submitted")
            # Rule 5d: one step, never a cascade.
            changed = {r for r, s in proj.state.items() if before.get(r) != s}
            outside = changed - reach(contract, proj, act)
            if outside:
                fail(f"{name} act {i} ({act['id']} {act['verb']}): changed {sorted(outside)} outside its one-step reach")
            for r in changed:
                trace.setdefault(r, []).append(proj.state[r])
        if crashed:
            continue
        expect = ex["expect"]
        if "refused" in expect:
            want = expect["refused"]
            refusals.add(want["code"])
            if want["code"] not in contract["refusals"]:
                fail(f"{name}: refusal {want['code']} is not listed in the contract's refusals")
            if refused is None:
                fail(f"{name}: expected refusal {want} but every act applied")
            elif refused[1].code != want["code"] or refused[0] != want["act_index"]:
                fail(f"{name}: expected refusal {want}, got act {refused[0]} {refused[1].code}: {refused[1]}")
        elif refused is not None:
            fail(f"{name}: act {refused[0]} refused: {refused[1].code}: {refused[1]}")
        for rid, st in expect.get("states", {}).items():
            if proj.state.get(rid) != st:
                fail(f"{name}: {rid} expected {st}, projected {proj.state.get(rid)}")
            if st in REMOVED_STATE_WORDS:
                fail(f"{name}: {rid} expects removed state word {st}")
        for pid, want_plan in expect.get("plans", {}).items():
            got = proj.record.get(pid, {})
            got_plan = {"members": got.get("members"), "waits_on": got.get("waits_on", [])}
            if got_plan != want_plan:
                fail(f"{name}: {pid} holds {got_plan}, expected {want_plan}")
        for rid, want_trace in expect.get("trace", {}).items():
            if trace.get(rid) != want_trace:
                fail(f"{name}: {rid} passed through {trace.get(rid)}, expected {want_trace}")
        if f"contract/examples/{name}" == NO_LOOP_EXAMPLE:
            check_no_loop_example(name, ex, trace, refused)
        exercised |= proj.applied
    if not (ROOT.parent / NO_LOOP_EXAMPLE).exists():
        fail(f"examples: {NO_LOOP_EXAMPLE} (rule 5 worked example) is missing")
    return exercised, refusals


def check_no_loop_example(name: str, ex: dict, trace: dict, refused) -> None:
    """Rule 5 worked example: assured, a later does_not_hold, a fix, a new
    Witness, holds again; the Oracle superseded without losing assurance; a
    refined Witness judged like any other; and a rejudge of a judged pair
    refused, so the loop never starts."""
    acts = ex["acts"]
    verbs = [a["verb"] for a in acts]
    promises = [r for r in trace if r.startswith("P-")]
    if len(promises) != 1 or trace[promises[0]] != ["asserted", "assured", "asserted", "assured"]:
        fail(f"{name}: the Promise must pass asserted, assured, asserted, assured; got {trace}")
    if "refine" not in verbs:
        fail(f"{name}: rule 5e needs a Witness made by refine")
    if not any(a["verb"] == "supersede" and a["payload"]["target"].startswith("O-") for a in acts):
        fail(f"{name}: rule 5c needs a superseded Oracle")
    if refused is None or refused[1].code != "already_judged" or refused[0] != len(acts) - 1:
        fail(f"{name}: rule 5b needs the last act to be a refused rejudge of a judged pair")


def check_manifest() -> None:
    import hashlib

    manifest = json.loads((ROOT.parent / "manifest.json").read_text())
    listed = {e["path"]: e["sha256"] for e in manifest.get("contract", [])}
    for p in (PROSE, CONTRACT, SCHEMA):
        rel = str(p.relative_to(ROOT.parent))
        digest = hashlib.sha256(p.read_bytes()).hexdigest()
        if listed.get(rel) != digest:
            fail(f"manifest: {rel} digest {listed.get(rel)} != file {digest}")
    version = (ROOT.parent / "VERSION").read_text().strip()
    if manifest.get("version") != version:
        fail(f"manifest: version {manifest.get('version')} != VERSION {version}")


def main() -> int:
    for p in (PROSE, CONTRACT, SCHEMA):
        if not p.exists():
            fail(f"missing {p.relative_to(ROOT.parent)}")
    if errors:
        return report()
    text = PROSE.read_text()
    contract = yaml.safe_load(CONTRACT.read_text())
    schema = json.loads(SCHEMA.read_text())
    broken = False
    for step in (
        lambda: check_contract(contract),
        lambda: check_prose(text, contract),
        lambda: check_schema(schema, contract),
        check_manifest,
    ):
        try:
            step()
        except (KeyError, TypeError, AttributeError, IndexError) as e:
            fail(f"structure: {type(e).__name__} {e}")
            broken = True
    if broken:
        return report()
    exercised, refusals = check_examples(schema, contract)
    for t in contract["transitions"]:
        for v in t["by"]:
            keys = {(t["noun"], f, t["to"], v) for f in (t["from"] or [None])}
            if not keys & exercised:
                fail(f"transition {t['noun']} {t['from']} -> {t['to']} by {v} is exercised by no example")
    for code in contract["refusals"]:
        if code not in refusals:
            fail(f"refusal {code} is exercised by no example")
    return report()


def report() -> int:
    if errors:
        for e in errors:
            print("FAIL", e)
        print(f"{len(errors)} disagreement(s)")
        return 1
    print("OK: prose, contract, schema and examples agree")
    return 0


if __name__ == "__main__":
    sys.exit(main())
